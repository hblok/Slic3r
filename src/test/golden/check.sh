#!/bin/sh
# Golden G-code check: slice the test models and compare with the stored output.
# A difference means slicing behaviour changed, not that it is wrong. If the change
# is intended, run with --update, review `git diff`, and commit the new output.
#
# Usage: check.sh path/to/slic3r [--update]
set -eu

slicer=$(realpath "$1")
update=${2:-}
cd "$(dirname "$0")" # relative model paths keep the output machine independent
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
failed=0

check() { # name model [options...]
    name=$1 model=$2
    shift 2
    # fixed thread count: it is written into the G-code and defaults to the core count
    "$slicer" -g "$model" --threads 4 "$@" -o "$tmp/$name.raw" >"$tmp/$name.log" 2>&1 &&
        [ -s "$tmp/$name.raw" ] || { echo "FAIL $name: slicing failed"; cat "$tmp/$name.log"; failed=1; return; }
    # drop the two header lines that carry the time and the commit
    grep -v -e '^; generated by ' -e '^; Git Commit: ' "$tmp/$name.raw" >"$tmp/$name.gcode"
    if [ "$update" = --update ]; then
        cp "$tmp/$name.gcode" "expected/$name.gcode"
        echo "updated $name"
    elif diff -u "expected/$name.gcode" "$tmp/$name.gcode" >"$tmp/$name.diff"; then
        echo "ok   $name"
    else
        echo "FAIL $name: output differs (first 40 lines of the diff)"
        head -40 "$tmp/$name.diff"
        failed=1
    fi
}

box=../inputs/test_cli/20mmbox.stl
check box_default $box
check box_tuned $box --nozzle-diameter 0.4 --layer-height 0.2 --first-layer-height 0.2 \
    --fill-pattern gyroid --fill-density 20% --brim-width 5 --retract-length 5 \
    --center 110,110 --gcode-comments
profiles=../../../profiles
check ender5pro_box $box --load $profiles/printer/Ender-5-Pro.ini \
    --load $profiles/filament/Ender-5-Pro-PLA.ini --load $profiles/print/Ender-5-Pro-0.20mm.ini
# Ender profiles with support on a 3-layer raft: most of the support code in one run
check ender5pro_table_raft table.stl --load $profiles/printer/Ender-5-Pro.ini \
    --load $profiles/filament/Ender-5-Pro-PLA.ini --load $profiles/print/Ender-5-Pro-0.20mm.ini \
    --support-material --raft-layers 3
# Overhang with the default (pillars) support; matches the Perl pipeline in
# filament per role (plan/baseline.md).
check table_support table.stl --support-material --gcode-comments
# CLI transforms run before the objects have instances (they crashed until 2026-11-27)
check box_transforms $box --scale 1.5 --rotate 30 --rotate-x 90 --scale-to-fit 25,25,25
check box_duplicate_grid $box --duplicate-grid 2,2

exit $failed
