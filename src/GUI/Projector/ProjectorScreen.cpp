void ProjectorSettings::load(const wxString& file) {
    std::ifstream in(file.ToUTF8().data());
    std::map<std::string, std::string> values;
    for (std::string line; std::getline(in, line); ) {
        const size_t eq {line.find(" = ")};
        if (line.empty() || line[0] == '#' || eq == std::string::npos) continue;
        values[line.substr(0, eq)] = line.substr(eq + 3);
    }
    auto number = [&values](const char* key, double& field) {
        double value;
        if (values.count(key) > 0 && wxString(values[key]).ToCDouble(&value)) field = value;
    };
    double flag {0};
    number("display", flag = this->display); this->display = static_cast<int>(flag);
    number("show_bed", flag = this->show_bed); this->show_bed = flag != 0;
    number("invert_y", flag = this->invert_y); this->invert_y = flag != 0;
    number("bottom_layers", flag = this->bottom_layers); this->bottom_layers = static_cast<int>(flag);
    number("zoom", this->zoom);
    number("exposure_time", this->exposure_time);
    number("bottom_exposure_time", this->bottom_exposure_time);
    number("settle_time", this->settle_time);
    number("z_lift", this->z_lift);
    number("z_lift_speed", this->z_lift_speed);
    if (values.count("offset") > 0) {
        const wxString offset {values["offset"]};
        offset.BeforeFirst(',').ToCDouble(&this->offset_x);
        offset.AfterFirst(',').ToCDouble(&this->offset_y);
    }
}

void ProjectorSettings::save(const wxString& file) const {
    std::ofstream out(file.ToUTF8().data());
    auto number = [](double value) { return wxString::FromCDouble(value).ToStdString(); };
    // the Perl GUI's keys and format
    out << "# generated by Slic3r " << SLIC3R_VERSION << "\n"
        << "bottom_exposure_time = " << number(bottom_exposure_time) << "\n"
        << "bottom_layers = " << bottom_layers << "\n"
        << "display = " << display << "\n"
        << "exposure_time = " << number(exposure_time) << "\n"
        << "invert_y = " << invert_y << "\n"
        << "offset = " << number(offset_x) << "," << number(offset_y) << "\n"
        << "settle_time = " << number(settle_time) << "\n"
        << "show_bed = " << show_bed << "\n"
        << "z_lift = " << number(z_lift) << "\n"
        << "z_lift_speed = " << number(z_lift_speed) << "\n"
        << "zoom = " << number(zoom) << "\n";
}

ProjectorScreen::ProjectorScreen() :
    wxFrame(nullptr, wxID_ANY, _("Projector"), wxDefaultPosition, wxDefaultSize, wxBORDER_NONE | wxFRAME_NO_TASKBAR)
{
    this->_canvas = new wxPanel(this);
    this->_canvas->SetBackgroundStyle(wxBG_STYLE_PAINT);
    this->_canvas->Bind(wxEVT_PAINT, [this](wxPaintEvent&) { this->_paint(); });
    this->_canvas->Bind(wxEVT_SIZE, [this](wxSizeEvent& e) { this->_canvas->Refresh(); e.Skip(); });
    auto* sizer {new wxBoxSizer(wxVERTICAL)};
    sizer->Add(this->_canvas, 1, wxEXPAND);
    this->SetSizer(sizer);
}

void ProjectorScreen::set_source(const SLAPrint* print, const std::vector<Pointf>& bed, const ProjectorSettings* settings) {
    this->_print = print;
    this->_bed = bed;
    this->_settings = settings;
    this->_layer = -1;
    this->_canvas->Refresh();
}

void ProjectorScreen::reposition() {
    const int display {this->_settings != nullptr ? this->_settings->display : 0};
    const wxRect area {wxDisplay(display >= 0 && display < static_cast<int>(wxDisplay::GetCount()) ? display : 0).GetGeometry()};
    this->SetSize(area);
    this->Layout();
    this->_canvas->Refresh();
}

void ProjectorScreen::project(int layer) {
    this->_layer = layer;
    this->_canvas->Refresh();
    this->_canvas->Update();
}

void ProjectorScreen::_paint() {
    wxAutoBufferedPaintDC dc(this->_canvas);
    dc.SetBackground(*wxBLACK_BRUSH);
    dc.Clear();
    const wxSize size {this->_canvas->GetClientSize()};
    if (this->_settings == nullptr || this->_bed.size() < 3 || size.x <= 1 || size.y <= 1) return;
    const ProjectorSettings& settings {*this->_settings};

    Polygon bed;
    for (const auto& p : this->_bed) bed.points.push_back(Point::new_scale(p.x, p.y));
    const BoundingBox bb {bed.bounding_box()};
    // pixels per mm: the bed fills the screen, then the zoom
    double scale {std::min(size.x / unscale(bb.size().x), size.y / unscale(bb.size().y))};
    if (settings.zoom > 0) scale *= settings.zoom / 100;
    const double zero_x {size.x / 2. - (unscale(bb.center().x) - settings.offset_x) * scale};
    const double zero_y {size.y / 2. - (unscale(bb.center().y) - settings.offset_y) * scale};
    auto pixel = [&](double x, double y) {
        const double px {x * scale + zero_x}, py {y * scale + zero_y};
        return wxPoint(static_cast<int>(px), static_cast<int>(settings.invert_y ? py : size.y - py));
    };
    auto points = [&](const Points& in) {
        std::vector<wxPoint> out;
        for (const auto& p : in) out.push_back(pixel(unscale(p.x), unscale(p.y)));
        return out;
    };
    auto polygon = [&](const Points& in, const wxBrush& brush) {
        std::vector<wxPoint> out {points(in)};
        if (out.size() < 3) return;
        dc.SetBrush(brush);
        dc.DrawPolygon(out.size(), out.data());
    };

    if (settings.show_bed) {
        dc.SetPen(wxPen(*wxRED, 2));
        polygon(bed.points, *wxTRANSPARENT_BRUSH);
        dc.SetPen(wxPen(*wxRED, 1));
        Polylines grid;
        auto line = [&grid](coord_t ax, coord_t ay, coord_t bx, coord_t by) {
            Polyline l;
            l.points = {Point(ax, ay), Point(bx, by)};
            grid.push_back(l);
        };
        const coord_t step {scale_(10)};
        for (coord_t x = bb.min.x - (bb.min.x % step) + step; x < bb.max.x; x += step) line(x, bb.min.y, x, bb.max.y);
        for (coord_t y = bb.min.y - (bb.min.y % step) + step; y < bb.max.y; y += step) line(bb.min.x, y, bb.max.x, y);
        for (const auto& l : intersection_pl(grid, Polygons{bed})) {
            if (l.points.size() < 2) continue;
            const auto ends {points({l.points.front(), l.points.back()})};
            dc.DrawLine(ends[0], ends[1]);
        }
        dc.SetPen(wxPen(*wxWHITE, 4));
        dc.DrawLine(pixel(0, 0), pixel(10, 0));
        dc.DrawLine(pixel(0, 0), pixel(0, 10));
        dc.SetTextForeground(*wxWHITE);
        dc.SetFont(wxFont(20, wxFONTFAMILY_DEFAULT, wxFONTSTYLE_NORMAL, wxFONTWEIGHT_NORMAL));
        dc.DrawText("X", pixel(10, 0));
        dc.DrawText("Y", pixel(0, 10) + wxPoint(-20, -10));
    }

    if (this->_print == nullptr || this->_layer < 0 || this->_layer >= static_cast<int>(this->_print->layers.size())) return;
    const SLAPrint::Layer& layer {this->_print->layers[this->_layer]};
    dc.SetPen(wxPen(*wxWHITE, 1));
    auto expolygons = [&](const ExPolygons& in) {
        for (const auto& ex : in) {
            polygon(ex.contour.points, *wxWHITE_BRUSH);
            for (const auto& hole : ex.holes) polygon(hole.points, *wxBLACK_BRUSH);
        }
    };
    if (layer.solid) {
        expolygons(layer.slices.expolygons);
    } else {
        // perimeters first: their holes are painted black
        expolygons(layer.perimeters.expolygons);
        expolygons(layer.solid_infill.expolygons);
        expolygons(union_ex(layer.infill.grow()));
    }
    // support pillars, with a conic tip
    const double pillar {this->_print->config.support_material_extrusion_width.get_abs_value(this->_print->config.layer_height.value) / 2};
    dc.SetBrush(*wxWHITE_BRUSH);
    for (const auto& support : this->_print->sm_pillars) {
        const size_t at {static_cast<size_t>(this->_layer)};
        if (support.top_layer < at || support.bottom_layer > at) continue;
        const double radius {std::min(pillar, (support.top_layer - at + 1) * this->_print->config.layer_height.value)};
        dc.DrawCircle(pixel(unscale(support.x), unscale(support.y)), static_cast<int>(radius * scale));
    }
}

