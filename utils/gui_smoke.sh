#!/bin/sh
# GUI smoke test for the Perl GUI: start it under Xvfb, load a model, tick support
# material, export G-code, open the preview, and check that the export matches what
# the command line produces with the same settings.
#
# Needs a built XS module (xs/blib), Xvfb, xdotool and ImageMagick (import).
# There is no window manager, so clicks go to fixed coordinates inside the default-size
# main window (760x490) and the wizard. Re-measure them if the layout changes; the
# screenshots in OUTDIR show where things are.
#
# Usage: utils/gui_smoke.sh OUTDIR   (screenshots, logs and G-code are written there)
set -eu
cd "$(dirname "$0")/.."
out=$(realpath -m "$1")
mkdir -p "$out"
export PERL5LIB="$PWD/xs/blib/arch:$PWD/xs/blib/lib${PERL5LIB:+:$PERL5LIB}"
export DISPLAY=":${SMOKE_DISPLAY:-99}"
model=src/test/golden/table.stl
datadir=$(mktemp -d)
gui= xvfb=
trap 'kill $gui $xvfb 2>/dev/null || :; rm -rf "$datadir"' EXIT

shot() { import -window root "$out/$1.png"; }
wait_window() { # name seconds: print the first matching window id
    w=$(timeout "$2" xdotool search --sync --onlyvisible --name "$1") && echo "$w" | head -1
}
click() { xdotool mousemove --window "$1" "$2" "$3" click 1; } # window x y
fail() { echo "FAIL: $*"; shot fail; exit 1; }

Xvfb "$DISPLAY" -screen 0 1600x1000x24 >"$out/xvfb.log" 2>&1 & xvfb=$!
sleep 2
# -o only presets the file name in the save dialog, so nothing has to be typed there
timeout 180 perl slic3r.pl --gui --datadir "$datadir" -o "$out/gui.gcode" "$model" >"$out/gui.log" 2>&1 & gui=$!

# a fresh data directory starts the configuration wizard; cancel it
wizard=$(wait_window "Configuration Assistant" 60) || fail "wizard did not open"
sleep 2
click "$wizard" 750 328               # "Cancel"
sleep 4
main=$(wait_window "^Slic3r$" 10) || fail "main window not found"
click "$main" 749 318                 # "Generate support material"
sleep 2
shot 1_loaded

click "$main" 684 248                 # "Export G-code..."
wait_window "Save G-code file as:" 30 >/dev/null || fail "save dialog did not open"
sleep 2
xdotool key Return
for _ in $(seq 120); do [ -s "$out/gui.gcode" ] && break; sleep 1; done
[ -s "$out/gui.gcode" ] || fail "no G-code exported"
sleep 3
shot 2_exported

click "$main" 178 454                 # "Preview" tab
sleep 5
shot 3_preview
kill $gui

perl slic3r.pl --datadir "$datadir" --support-material "$model" -o "$out/cli.gcode" >"$out/cli.log" 2>&1
grep -v '^; generated by ' "$out/gui.gcode" >"$out/gui.cmp"
grep -v '^; generated by ' "$out/cli.gcode" >"$out/cli.cmp"
cmp -s "$out/gui.cmp" "$out/cli.cmp" || fail "GUI export differs from the CLI (diff $out/gui.cmp $out/cli.cmp)"
echo "ok   GUI export matches the CLI ($(grep -c '^G1.*E' "$out/gui.gcode") extrusion moves)"
