#!/bin/sh
# Smoke test for the C++ GUI (wxWidgets), under Xvfb: start it with a model, click
# "Export G-code…", and check that the G-code equals the C++ command line's, that the
# GUI kept running and that it reported no wx assertions. Twice: with an empty data
# directory (defaults), and with the Ender 5 Pro presets selected through slic3r.ini
# (the Perl GUI's settings file). Then the preset editor: change the layer height in the
# Print Settings tab, export (must equal the CLI with that change), and save the preset
# under a new name. Then the preview: both toolpath tabs slice and draw (counted by
# colour), the slider cuts layers off, an export afterwards still equals the CLI, and the
# preview empties with the plate.
#
# There is no window manager, so the click goes to fixed coordinates inside the
# default-size window; re-measure them if the layout changes (see the screenshots).
#
# Needs the GUI build (cmake -S src -B build-gui -DEnable_GUI=ON), the CLI build
# (build/slic3r), Xvfb, xdotool and ImageMagick.
# Usage: utils/cpp_gui_smoke.sh path/to/gui/slic3r path/to/cli/slic3r OUTDIR
set -eu
# hang guard: after 290 s the whole run is killed, Xvfb and the program included
[ "${GUI_TEST_GUARD:-}" = "$0" ] || GUI_TEST_GUARD=$0 exec timeout -v -k 5 290 "$0" "$@"
gui_bin=$(realpath "$1")
cli_bin=$(realpath "$2")
out=$(realpath -m "$3")
cd "$(dirname "$0")/.."
root=$PWD
model=$root/src/test/golden/table.stl
# an earlier run's files break the next one (the save dialogs ask to replace them):
# start clean, but only ever remove a directory that a test run made
if [ -e "$out/.gui-test" ]; then
    rm -rf "$out"
elif [ -n "$(ls -A "$out" 2>/dev/null)" ]; then
    echo "$out is not empty and not from a test run; not touching it" >&2; exit 2
fi
mkdir -p "$out"; : >"$out/.gui-test"
export DISPLAY=":${SMOKE_DISPLAY:-98}"
export HOME="$out/home"
mkdir -p "$HOME"
gui= xvfb=
trap 'kill $gui $xvfb 2>/dev/null || :' EXIT

fail() { echo "FAIL: $*"; import -window root "$out/fail.png"; exit 1; }

Xvfb "$DISPLAY" -screen 0 1280x900x24 >"$out/xvfb.log" 2>&1 & xvfb=$!
sleep 2

click() { xdotool mousemove --window "$main" "$1" "$2" click 1; sleep 1; }

run() { # name datadir cli-options...   ($edit, if set, runs before the export)
    name=$1 datadir=$2
    shift 2
    # shellcheck disable=SC2086
    "$gui_bin" --datadir "$datadir" -o "$out/$name.gui.gcode" ${gui_options:-} "$model" >"$out/$name.gui.log" 2>&1 & gui=$!
    sleep 10
    import -window root "$out/$name.loaded.png"
    kill -0 "$gui" 2>/dev/null || fail "$name: the GUI exited (see $out/$name.gui.log)"
    main=$(xdotool search --onlyvisible --name Slic3r | head -1)
    [ -z "${edit:-}" ] || $edit
    xdotool mousemove --window "$main" 712 249 click 1   # "Export G-code…"
    for i in $(seq 1 60); do [ -s "$out/$name.gui.gcode" ] && break; sleep 1; done
    sleep 1
    import -window root "$out/$name.exported.png"
    [ -z "${after:-}" ] || $after
    kill -0 "$gui" 2>/dev/null || fail "$name: the GUI exited (see $out/$name.gui.log)"
    kill "$gui" 2>/dev/null || :
    wait "$gui" 2>/dev/null || :
    [ -s "$out/$name.gui.gcode" ] || fail "$name: no G-code exported"
    if grep -q "wx assertion" "$out/$name.gui.log"; then
        grep "wx assertion" "$out/$name.gui.log" | sort | uniq -c
        fail "$name: wx assertions"
    fi
    "$cli_bin" -g "$@" "$model" -o "$out/$name.cli.gcode" >"$out/$name.cli.log" 2>&1
    for f in gui cli; do
        grep -v -e '^; generated by ' -e '^; Git Commit: ' "$out/$name.$f.gcode" >"$out/$name.$f.cmp"
    done
    cmp -s "$out/$name.gui.cmp" "$out/$name.cli.cmp" \
        || fail "$name: GUI export differs from the CLI (diff $out/$name.gui.cmp $out/$name.cli.cmp)"
    echo "ok   $name: C++ GUI export equals the CLI ($(grep -c '^G1 .*E' "$out/$name.gui.cmp") extrusion moves)"
}

mkdir -p "$out/data-empty"
: >"$out/data-empty/slic3r.ini"                          # not a first start: no wizard
run defaults "$out/data-empty"

p=$root/profiles
mkdir -p "$out/data-ender"
cp -r "$p/print" "$p/filament" "$p/printer" "$out/data-ender/"
printf '[presets]\nprint = Ender-5-Pro-0.20mm\nfilament = Ender-5-Pro-PLA\nprinter = Ender-5-Pro\n' \
    >"$out/data-ender/slic3r.ini"
run ender "$out/data-ender" --load "$p/printer/Ender-5-Pro.ini" \
    --load "$p/filament/Ender-5-Pro-PLA.ini" --load "$p/print/Ender-5-Pro-0.20mm.ini"
grep -q '^print = Ender-5-Pro-0.20mm' "$out/data-ender/slic3r.ini" || fail "slic3r.ini lost the presets"

# options on the GUI's command line apply on top of the presets
cp -r "$out/data-ender" "$out/data-options"
gui_options="--fill-density 40% --skirts 3" run options "$out/data-options" --load "$p/printer/Ender-5-Pro.ini" \
    --load "$p/filament/Ender-5-Pro-PLA.ini" --load "$p/print/Ender-5-Pro-0.20mm.ini" --fill-density 40% --skirts 3

# the preset editor: layer height 0.3 in the Print Settings tab, then "Save as" My-Print
edit_layer_height() {
    click 230 43                                          # "Print Settings" tab
    click 472 110                                         # "Layer height"
    xdotool key ctrl+a; xdotool type 0.3; xdotool key Return; sleep 1
    import -window root "$out/editor.edited.png"
    click 40 43                                           # back to the plater
}
save_as_my_print() {
    click 230 43
    click 167 85; sleep 2                                 # save button, then the name dialog
    xdotool type My-Print; xdotool key Return; sleep 3
    import -window root "$out/editor.saved.png"
}
# the preview: the canvas left of the slider, pixels that match an ImageMagick condition
pixels() { # name condition
    import -window root "$out/$1.png"
    # (ImageMagick 7.1.1 prints a line "list" before the number)
    convert "$out/$1.png" -crop 335x300+3+123 +repage -fx "($2)?1:0" -format '%[fx:round(mean*w*h)]' info: | tail -n 1
}
yellow='r-b>0.25 && g-b>0.25'   # perimeters in the 3D preview (lit)
red='r-g>0.3 && r-b>0.3'        # perimeters in the 2D toolpaths
check_preview() {
    click 171 447; sleep 5                                # "Preview" tab: slices
    all=$(pixels preview.3d "$yellow")
    [ "$all" -gt 500 ] || fail "preview: no toolpaths in 3D ($all pixels)"
    click 378 350                                         # slider: down to the table's post
    low=$(pixels preview.3d-low "$yellow")
    [ "$low" -lt $((all / 2)) ] || fail "preview: the slider changes nothing ($all, then $low pixels)"
    click 260 447                                         # "Toolpaths" tab
    flat=$(pixels preview.2d "$red")
    [ "$flat" -gt 500 ] || fail "preview: no 2D toolpaths ($flat pixels)"
    echo "ok   preview: 3D ($all pixels, $low at a low layer) and 2D ($flat pixels)"
}
check_preview_empties() {
    click 227 88; sleep 1                                 # "Delete All", on the Toolpaths tab
    left=$(pixels preview.deleted "$red")
    [ "$left" -eq 0 ] || fail "preview: still drawn after Delete All ($left pixels)"
    echo "ok   preview: empty after Delete All"
}
cp -r "$out/data-ender" "$out/data-preview"
edit=check_preview after=check_preview_empties run preview "$out/data-preview" \
    --load "$p/printer/Ender-5-Pro.ini" --load "$p/filament/Ender-5-Pro-PLA.ini" \
    --load "$p/print/Ender-5-Pro-0.20mm.ini"

cp -r "$out/data-ender" "$out/data-editor"
edit=edit_layer_height after=save_as_my_print run editor "$out/data-editor" \
    --load "$p/printer/Ender-5-Pro.ini" --load "$p/filament/Ender-5-Pro-PLA.ini" \
    --load "$p/print/Ender-5-Pro-0.20mm.ini" --layer-height 0.3
grep -q '^layer_height = 0.3' "$out/data-editor/print/My-Print.ini" || fail "editor: My-Print.ini not saved with the change"
grep -q '^print = My-Print' "$out/data-editor/slic3r.ini" || fail "editor: the saved preset is not selected"
echo "ok   editor: saved as My-Print and selected"

# unsaved changes at quit: Cancel stays open, Discard writes nothing, Save writes. A
# material saved in between must not drop the print preset's change.
start_modified() { # datadir
    cp -r "$out/data-ender" "$1"
    "$gui_bin" --datadir "$1" >"$1.log" 2>&1 & gui=$!
    sleep 8
    main=$(xdotool search --onlyvisible --name Slic3r | head -1)
    edit_layer_height
}
quit_asks() { # name: File > Quit (the last entry), then the dialog gets the keyboard
    click 19 12; xdotool key Up; sleep 0.3; xdotool key Return; sleep 2
    import -window root "$out/$1.png"
    dialog=$(xdotool search --onlyvisible --name '^Unsaved Changes$') || fail "$1: no question"
    xdotool windowfocus "$dialog"; sleep 0.3
}
exited() { sleep 3; ! kill -0 "$gui" 2>/dev/null || fail "$1: the GUI did not quit"; wait "$gui" || :; }
ini=print/Ender-5-Pro-0.20mm.ini

start_modified "$out/data-quit-save"
click 361 43; click 167 85; sleep 1                       # "Material Settings": save under
xdotool type My-Material; xdotool key Return; sleep 2     # a new name
click 40 43
quit_asks quit.cancel
xdotool key Escape; sleep 1
kill -0 "$gui" 2>/dev/null || fail "quit: Cancel closed the program"
quit_asks quit.save
xdotool key Return                                        # "Save" is the default
exited "quit, Save"
grep -q '^layer_height = 0.3' "$out/data-quit-save/$ini" || fail "quit: Save did not write the change"
echo "ok   quit: asked (also after saving another preset), Cancel, Save"

start_modified "$out/data-quit-discard"
quit_asks quit.discard
xdotool mousemove --window "$dialog" 74 131 click 1       # "Discard"
exited "quit, Discard"
cmp -s "$p/$ini" "$out/data-quit-discard/$ini" || fail "quit: Discard changed the preset file"
echo "ok   quit: Discard"
