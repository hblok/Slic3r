#!/bin/sh
# Smoke test for the C++ GUI (wxWidgets): start it under Xvfb with an empty data
# directory and a model, check that it runs without wx assertions, click
# "Export G-code…", and check that the G-code equals the C++ command line's.
# The Perl GUI has utils/gui_smoke.sh.
#
# There is no window manager, so the click goes to fixed coordinates inside the
# default-size window; re-measure them if the layout changes (see the screenshots).
#
# Needs the GUI build (cmake -S src -B build-gui -DEnable_GUI=ON), the CLI build
# (build/slic3r), Xvfb, xdotool and ImageMagick.
# Usage: utils/cpp_gui_smoke.sh path/to/gui/slic3r path/to/cli/slic3r OUTDIR
set -eu
gui_bin=$(realpath "$1")
cli_bin=$(realpath "$2")
out=$(realpath -m "$3")
cd "$(dirname "$0")/.."
model=$PWD/src/test/golden/table.stl
mkdir -p "$out"
export DISPLAY=":${SMOKE_DISPLAY:-98}"
export HOME="$out/home"  # the data directory (~/.Slic3r) starts empty
mkdir -p "$HOME"
gui= xvfb=
trap 'kill $gui $xvfb 2>/dev/null || :' EXIT

shot() { import -window root "$out/$1.png"; }
fail() { echo "FAIL: $*"; shot fail; exit 1; }

Xvfb "$DISPLAY" -screen 0 1280x900x24 >"$out/xvfb.log" 2>&1 & xvfb=$!
sleep 2
"$gui_bin" -o "$out/gui.gcode" "$model" >"$out/gui.log" 2>&1 & gui=$!
sleep 10
shot 1_loaded
kill -0 "$gui" 2>/dev/null || fail "the GUI exited (see $out/gui.log)"

main=$(xdotool search --onlyvisible --name Slic3r | head -1)
xdotool mousemove --window "$main" 712 249 click 1   # "Export G-code…"
for i in $(seq 1 60); do [ -s "$out/gui.gcode" ] && break; sleep 1; done
sleep 1
shot 2_exported
[ -s "$out/gui.gcode" ] || fail "no G-code exported"

if grep -q "wx assertion" "$out/gui.log"; then
    grep "wx assertion" "$out/gui.log" | sort | uniq -c
    fail "wx assertions"
fi

"$cli_bin" -g "$model" -o "$out/cli.gcode" >"$out/cli.log" 2>&1
for f in gui cli; do
    grep -v -e '^; generated by ' -e '^; Git Commit: ' "$out/$f.gcode" >"$out/$f.cmp"
done
cmp -s "$out/gui.cmp" "$out/cli.cmp" || fail "GUI export differs from the CLI (diff $out/gui.cmp $out/cli.cmp)"
echo "ok   C++ GUI export equals the CLI ($(grep -c '^G1 .*E' "$out/gui.cmp") extrusion moves)"
